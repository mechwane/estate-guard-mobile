// Access code detail sheet: real scannable QR of the guest code, the code
// itself, who generated it, validity window and the generated → checked in →
// checked out lifecycle.
import { useEffect, useState } from "react";
import QRCode from "qrcode";
import { format } from "date-fns";
import { Check, Copy } from "lucide-react";
import { toast } from "sonner";
import { SheetModal } from "@/components/ui-kit";

export type AccessCode = {
  id: string;
  code: string;
  guest_name: string;
  status: string;
  visit_time: string;
  expires_at: string;
  checked_in_at: string | null;
  checked_out_at: string | null;
  num_guests: number | null;
  vehicle_number: string | null;
  purpose: string | null;
};

export function codeState(c: AccessCode): "active" | "used" | "expired" | "revoked" {
  if (c.status === "revoked") return "revoked";
  if (c.checked_out_at || c.status === "used") return "used";
  if (new Date(c.expires_at).getTime() < Date.now() || c.status === "expired") return "expired";
  return "active";
}

const stateCopy: Record<string, { label: string; cls: string }> = {
  active: { label: "Active Code", cls: "text-[color:var(--color-success)]" },
  used: { label: "Used Code", cls: "text-primary" },
  expired: { label: "Expired Code", cls: "text-destructive" },
  revoked: { label: "Revoked Code", cls: "text-destructive" },
};

export function AccessCodeDetail({
  invite,
  hostName,
  hostAddress,
  onClose,
}: {
  invite: AccessCode;
  hostName?: string | null;
  hostAddress?: string | null;
  onClose: () => void;
}) {
  const [qr, setQr] = useState<string | null>(null);
  const [copied, setCopied] = useState(false);
  const state = codeState(invite);
  const tone = stateCopy[state]!;

  useEffect(() => {
    let alive = true;
    QRCode.toDataURL(invite.code, { width: 320, margin: 1, errorCorrectionLevel: "M" })
      .then((url) => alive && setQr(url))
      .catch(() => alive && setQr(null));
    return () => {
      alive = false;
    };
  }, [invite.code]);

  const copy = async () => {
    await navigator.clipboard.writeText(invite.code);
    setCopied(true);
    toast.success("Code copied");
    setTimeout(() => setCopied(false), 1500);
  };

  const stamp = (d: string | null) => (d ? format(new Date(d), "EEEE, d MMM yyyy 'AT' p") : "—");

  return (
    <SheetModal open title="Access code" onClose={onClose} width="lg">
      <div className="text-center">
        <div className="mx-auto grid h-40 w-40 place-items-center rounded-2xl border border-border bg-white p-2">
          {qr ? (
            <img src={qr} alt={`QR code for access code ${invite.code}`} className="h-full w-full" />
          ) : (
            <span className="text-[11px] text-muted-foreground">Generating…</span>
          )}
        </div>
        <div className="mt-3 text-3xl font-bold tracking-wider text-foreground">{invite.code}</div>
        <div className={`text-xs font-medium ${tone.cls}`}>{tone.label}</div>
        <button
          onClick={copy}
          className="mt-3 inline-flex w-full items-center justify-center gap-2 rounded-lg border border-border bg-card px-4 py-2.5 text-sm font-medium hover:bg-muted"
        >
          Copy Code {copied ? <Check className="h-4 w-4" /> : <Copy className="h-4 w-4" />}
        </button>
      </div>

      <div className="mt-5 space-y-3">
        <div>
          <div className="text-xs font-semibold text-foreground">Generated By</div>
          <div className="mt-1.5 flex items-center gap-2.5 rounded-lg bg-muted/50 p-3">
            <span className="grid h-9 w-9 shrink-0 place-items-center rounded-full bg-primary/10 text-xs font-semibold text-primary">
              {(hostName || "?").slice(0, 1).toUpperCase()}
            </span>
            <div className="min-w-0">
              <div className="truncate text-sm font-medium">{hostName ?? "Resident"}</div>
              <div className="truncate text-[11px] text-muted-foreground">
                {hostAddress || "Resident of this estate"}
              </div>
            </div>
          </div>
        </div>

        <dl className="divide-y divide-border text-sm">
          <Row label="Guest" value={invite.guest_name} />
          <Row label="Valid From" value={stamp(invite.visit_time)} />
          <Row label="Expires On" value={stamp(invite.expires_at)} />
          <Row
            label="Expected Number of Guest"
            value={`${invite.num_guests ?? 1} Person${(invite.num_guests ?? 1) > 1 ? "s" : ""}`}
          />
          <Row label="Code Usage" value="One Time" />
          {invite.vehicle_number && <Row label="Vehicle" value={invite.vehicle_number} />}
          {invite.purpose && <Row label="Purpose" value={invite.purpose} />}
        </dl>

        <div className="rounded-xl border border-border p-4">
          <div className="text-xs font-semibold text-foreground">Movement</div>
          <div className="mt-4 flex items-start justify-between gap-2">
            <Step label="Generated" done at={invite.visit_time} />
            <Line done={!!invite.checked_in_at} />
            <Step label="Checked In" done={!!invite.checked_in_at} at={invite.checked_in_at} />
            <Line done={!!invite.checked_out_at} />
            <Step label="Checked Out" done={!!invite.checked_out_at} at={invite.checked_out_at} />
          </div>
        </div>
      </div>
    </SheetModal>
  );
}

function Row({ label, value }: { label: string; value: string }) {
  return (
    <div className="flex items-start justify-between gap-3 py-2">
      <dt className="text-muted-foreground">{label}</dt>
      <dd className="text-right text-foreground">{value}</dd>
    </div>
  );
}

function Line({ done }: { done: boolean }) {
  return (
    <span
      className={`mt-2.5 h-0.5 flex-1 rounded-full ${done ? "bg-primary" : "bg-border"}`}
      aria-hidden
    />
  );
}

function Step({ label, done, at }: { label: string; done: boolean; at?: string | null }) {
  return (
    <div className="flex w-20 shrink-0 flex-col items-center text-center">
      <span
        className={`grid h-5 w-5 place-items-center rounded-full border-2 ${
          done ? "border-primary bg-primary text-primary-foreground" : "border-border"
        }`}
      >
        {done && <Check className="h-3 w-3" />}
      </span>
      <span className="mt-1 text-[10px] font-medium text-muted-foreground">{label}</span>
      {at && (
        <span className="text-[9px] text-muted-foreground/80">{format(new Date(at), "d MMM p")}</span>
      )}
    </div>
  );
}
